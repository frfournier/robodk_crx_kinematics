"""Independent-seed family holdout, with strict FK at three physical scales.

Generated by the shared fixture generator; seed 20261010 is separate from the
frozen 20261009 performance corpus. Recorded rounded Cartesian observations are
excluded from scaling because their rounding errors would scale too.
"""
import ctypes

import numpy as np
import pytest

from crx_test_support import RobotT, check_solver_pose
from fixtures.generate_solver_cases import corpus

MODELS, REFERENCES, ALL_CASES = corpus(64, 28, 20261010)
CASES = [{**case, "name": "holdout:20261010:" + case["name"]}
         for case in ALL_CASES if case["group"] not in ("fixtures", "discovery-witnesses")]


@pytest.fixture(scope="module", params=[.001, 1., 1000.], ids=["small", "nominal", "large"])
def scaled_models(request):
    scale = request.param
    models, references, robots = [], [], []
    for source, reference in zip(MODELS, REFERENCES):
        model = {**source, "robot": source["robot"].copy()}
        table = model["robot"]
        # Model recognition snaps these nominal structural zeros before IK.
        # Apply that same 4096-epsilon-at-1-mm encoding budget before changing
        # units, so this tests kinematic scaling rather than off-family DH data.
        for column in (1, 3):
            values = table[10:16, column]
            values[np.isclose(values, 0, atol=4096*np.finfo(float).eps, rtol=0)] = 0
        table[10:16, 1] *= scale
        table[10:16, 3] *= scale
        table[9, :3] *= scale
        table[28, :3] *= scale
        robot = RobotT()
        ctypes.memmove(ctypes.byref(robot), table.ctypes.data, table.nbytes)
        models.append(model)
        robots.append(robot)
        derived = {key: value.copy() for key, value in reference.items()}
        derived["base"][:3, 3] *= scale
        derived["tool"][:3, 3] *= scale
        derived["dh"][:, 1] *= scale
        derived["dh"][:, 3] *= scale
        references.append(derived)
    return scale, (models, references, robots)


@pytest.mark.parametrize("case", CASES, ids=lambda case: case["name"])
def test_family_holdout(kinematics_lib, scaled_models, case):
    scale, models = scaled_models
    target = np.array(case["target"])
    target[:3, 3] *= scale
    commands = check_solver_pose(
        kinematics_lib, models, {**case, "target": target}, False)
    if case["group"] == "random":
        # Regular-pose branch coverage, not just existence of any valid answer.
        # Keep the established .009-degree witness-matching convention.
        for witness in case["witnesses"]:
            difference = (commands - np.degrees(witness) + 180) % 360 - 180
            assert np.any(np.max(abs(difference), axis=1) <= .009), case["name"]
